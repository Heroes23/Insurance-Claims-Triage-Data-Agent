-- Setting my database and schema: 
USE DATABASE INSURANCE_DB;
USE SCHEMA RAW;

-- Data Exploratory: 
SELECT * FROM AUTO_INSURANCE LIMIT 5; 

-- Snowflake setup for INSURANCE_DB. Run in a worksheet as ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;

-- 1. Warehouse (small, auto-suspends after 60s to save credits)
CREATE WAREHOUSE IF NOT EXISTS DE_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- 2. Schemas (RAW already exists)
CREATE SCHEMA IF NOT EXISTS INSURANCE_DB.ANALYTICS;

-- 3. Roles
CREATE ROLE IF NOT EXISTS TRANSFORMER;  -- ingest + dbt (read/write)
CREATE ROLE IF NOT EXISTS AGENT_RO;     -- agent + Streamlit (read-only)

GRANT USAGE ON WAREHOUSE DE_WH TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE DE_WH TO ROLE AGENT_RO;

-- 4. TRANSFORMER: full control of the project database
GRANT USAGE, CREATE SCHEMA ON DATABASE INSURANCE_DB TO ROLE TRANSFORMER;
GRANT ALL ON SCHEMA INSURANCE_DB.RAW TO ROLE TRANSFORMER;
GRANT ALL ON SCHEMA INSURANCE_DB.ANALYTICS TO ROLE TRANSFORMER;
GRANT ALL ON ALL TABLES IN SCHEMA INSURANCE_DB.RAW TO ROLE TRANSFORMER;
GRANT ALL ON FUTURE TABLES IN SCHEMA INSURANCE_DB.RAW TO ROLE TRANSFORMER;

-- 5. AGENT_RO: read-only, including objects dbt creates later
GRANT USAGE ON DATABASE INSURANCE_DB TO ROLE AGENT_RO;
GRANT USAGE ON ALL SCHEMAS IN DATABASE INSURANCE_DB TO ROLE AGENT_RO;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE INSURANCE_DB TO ROLE AGENT_RO;
GRANT SELECT ON ALL TABLES IN DATABASE INSURANCE_DB TO ROLE AGENT_RO;
GRANT SELECT ON FUTURE TABLES IN DATABASE INSURANCE_DB TO ROLE AGENT_RO;
GRANT SELECT ON ALL VIEWS IN DATABASE INSURANCE_DB TO ROLE AGENT_RO;
GRANT SELECT ON FUTURE VIEWS IN DATABASE INSURANCE_DB TO ROLE AGENT_RO;

-- 6. Give the roles to your user
GRANT ROLE TRANSFORMER TO USER ZAED2395;
GRANT ROLE AGENT_RO TO USER ZAED2395;

-- 7. Verify
SHOW GRANTS TO ROLE AGENT_RO;
SHOW GRANTS TO ROLE TRANSFORMER;

-- 8. Test TRANSFORMER (should work)
USE ROLE TRANSFORMER;
USE WAREHOUSE DE_WH;
SELECT COUNT(*) FROM INSURANCE_DB.RAW.AUTO_INSURANCE;

-- 9. Test AGENT_RO (select should work, create should FAIL)
USE ROLE AGENT_RO;
USE WAREHOUSE DE_WH;
SELECT COUNT(*) FROM INSURANCE_DB.RAW.AUTO_INSURANCE;
